function listSyllabusVideos({ semester, subjectCode, search }) {
  let list = [...SYLLABUS_VIDEO_CHAPTERS];

  if (semester) {
    list = list.filter((v) => Number(v.semesterNumber) === Number(semester));
  }
  if (subjectCode) {
    list = list.filter((v) => v.subjectCode.toLowerCase() === subjectCode.toLowerCase());
  }
  if (search) {
    const s = search.toLowerCase();
    list = list.filter(
      (v) =>
        v.title.toLowerCase().includes(s) ||
        v.description.toLowerCase().includes(s) ||
        v.subjectName.toLowerCase().includes(s) ||
        v.tags.some((t) => t.toLowerCase().includes(s))
    );
  }

  return list;
}

